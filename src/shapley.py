import itertools
import math


def calculate_shapley_values(lever_values):
    """
    Calculate Shapley values for negotiation levers.

    lever_values:
        Dictionary containing the estimated value contribution
        of each negotiation lever.

    This is a prototype attribution model.
    The values supplied here are illustrative and should
    eventually be calibrated using real procurement data.
    """

    players = list(lever_values.keys())

    n = len(players)

    shapley_values = {
        player: 0.0
        for player in players
    }

    def coalition_value(coalition):
        """
        Calculate the value generated by a coalition
        of negotiation levers.

        Prototype assumption:
        coalition value is the sum of individual
        lever values.
        """

        return sum(
            lever_values[player]
            for player in coalition
        )

    # --------------------------------------------------
    # Calculate Shapley values
    # --------------------------------------------------

    for player in players:

        other_players = [
            p for p in players
            if p != player
        ]

        for r in range(len(other_players) + 1):

            for coalition in itertools.combinations(
                other_players,
                r
            ):

                coalition = set(coalition)

                coalition_with_player = (
                    coalition | {player}
                )

                marginal_contribution = (
                    coalition_value(
                        coalition_with_player
                    )
                    -
                    coalition_value(
                        coalition
                    )
                )

                weight = (
                    math.factorial(r)
                    *
                    math.factorial(
                        n - r - 1
                    )
                    /
                    math.factorial(n)
                )

                shapley_values[player] += (
                    weight
                    *
                    marginal_contribution
                )

    return shapley_values