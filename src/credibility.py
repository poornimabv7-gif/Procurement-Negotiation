import pandas as pd


def assess_credibility(signals):
    """
    Assess the credibility of supplier signals.

    Uses the signal credibility score generated by
    the signalling analysis.

    Note:
    This is a prototype evidence-based assessment.
    It is NOT a calibrated probability of truthfulness.
    """

    result = signals.copy()

    def classify_credibility(score):

        if pd.isna(score):
            return "Unknown - Insufficient Evidence"

        if score >= 0.70:
            return "Credible - Can Be Considered"

        elif score >= 0.40:
            return "Partially Credible - Verify"

        else:
            return "Unverified - Do Not Rely Without Verification"

    result["credibility_assessment"] = (
        pd.to_numeric(
            result["signal_credibility_score"],
            errors="coerce"
        )
        .apply(classify_credibility)
    )

    def recommend_action(assessment):

        if assessment == "Credible - Can Be Considered":
            return "Use as negotiation input"

        elif assessment == "Partially Credible - Verify":
            return "Request supporting evidence"

        elif assessment == "Unverified - Do Not Rely Without Verification":
            return "Do not use as decision basis"

        return "Collect additional evidence"

    result["credibility_action"] = (
        result["credibility_assessment"]
        .apply(recommend_action)
    )

    return result